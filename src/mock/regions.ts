/*
 * 가상 취약도 산식 (분석 2의 실제 모형으로 교체될 자리)
 *   고령 요인    = (고령비율 - 0.15) / 0.30
 *   시간격차 요인 = (대중교통분 - 자가용분) / 90
 *   공급부족 요인 = 1 - 대중교통 공급 점수 / 100
 *   관외진료 요인 = 관외 진료 비율
 *   취약도 = 100 × (0.30 고령 + 0.30 시간격차 + 0.25 공급부족 + 0.15 관외진료)
 */
const clamp01 = (v: number) => Math.min(1, Math.max(0, v));

function score(r: Row) {
  const [, , , elderly, , supply, car, transit, outbound] = r;
  const f = {
    aging: clamp01((elderly - 0.15) / 0.3),
    gap: clamp01((transit - car) / 90),
    supply: clamp01(1 - supply / 100),
    outbound: clamp01(outbound),
  };
  const total = 100 * (0.3 * f.aging + 0.3 * f.gap + 0.25 * f.supply + 0.15 * f.outbound);
  return { total: Math.round(total), f, car };
}

/* 가상 유형 분류: 점수가 낮으면 '양호', 아니면 가장 두드러진 요인으로 유형을 정한다.
   실제 분석에서는 머신러닝 군집 결과가 들어간다. */
function classify(s: ReturnType<typeof score>): ClusterType {
  if (s.total < 45) return 'stable';
  if (s.car >= 28) return 'far_hospital';
  if (s.f.aging >= 0.85) return 'aging_isolated';
  return s.f.supply >= s.f.aging ? 'transit_poor' : 'aging_isolated';
}

